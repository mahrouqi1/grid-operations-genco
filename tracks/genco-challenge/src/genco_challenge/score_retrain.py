"""Score the OSC fixed-pipeline retrain (job B) zero-shot on the 15 held-out grids, next to the released checkpoint.

One command after ``bash slurm/sync_from_osc.sh genco-retrain`` (env ``grid-operations-genco``, repo root, one GPU):

    CUDA_VISIBLE_DEVICES=1 nice -n 10 python -m genco_challenge.score_retrain \\
        --out tracks/genco-challenge/results/<date>-genco-retrain-scoring

It registers each arm's ``final/best_model_state_dict.pt`` under ``experiments/genco-retrain/<arm>/`` as a model of
``ladder_eval`` (``retrain_fixed``, ``retrain_published``), runs ``ladder_eval.evaluate`` (graphkit's own evaluate,
unchanged, plus our label errors) on the same 15 grids and the same test scenarios as
``results/2026-10-07-genco-heldout-zeroshot``, and writes ``results.jsonl`` plus ``tally.md``: per model, the number
of grids where it beats DC on graphkit's active residual, on branch angle difference (raw prediction) and on |V|
(slack and PV magnitudes put back), with per-grid ratios to DC. Those are the counts the entry quotes for the
released checkpoint (residual 0 of 15, branch angle 1 of 15, |V| 13 of 15), so the rows compare like for like.

Normalizer: like ``zeroshot`` (the released pretrained checkpoint), the arms are evaluated with no normalizer file,
so all three use graphkit's default path. If an arm's ``final/`` holds ``normalizer_stats.pt`` it is recorded in the
run metadata but not used; pass ``--use-arm-normalizer`` to use it (a different protocol, labelled in the rows).

Control (run it before trusting the arms): ``--alias retrain_fixed=released`` points the arm name at the released
pretrained checkpoint. Its rows must equal the ``zeroshot`` rows to float noise; ``tally.md`` says whether they do.

What it does not do: few-shot fine-tuning of the arms on case118 (``python -m genco_challenge.fewshot``, see its
docstring) and the collapsed-label check under the pretraining mask
(``results/2026-10-09-collapsed-label-pretrain-mask/run_pretrain_mask.py``, which hardcodes the released checkpoint).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from genco_challenge import ladder_eval as LE

REPO = LE.REPO
HELDOUT15 = [
    "pglib_opf_case5_pjm", "pglib_opf_case14_ieee", "pglib_opf_case24_ieee_rts", "pglib_opf_case30_ieee",
    "pglib_opf_case39_epri", "pglib_opf_case57_ieee", "pglib_opf_case73_ieee_rts", "pglib_opf_case89_pegase",
    "pglib_opf_case118_ieee", "pglib_opf_case162_ieee_dtc", "pglib_opf_case240_pserc", "pglib_opf_case300_ieee",
    "pglib_opf_case1354_pegase", "pglib_opf_case2736sp_k", "pglib_opf_case3120sp_k",
]
ARMS = ("fixed", "published")


def register(run_root: Path, use_norm: bool, alias: dict[str, str]) -> dict[str, dict]:
    meta = {}
    for arm in ARMS:
        name = f"retrain_{arm}"
        if name in alias:
            src = alias[name]
            if src != "released":
                raise SystemExit(f"--alias supports only <arm>=released, got {src}")
            LE.MODELS[name] = LE.MODELS["zeroshot"]
            meta[name] = {"alias_of": "zeroshot", "state_dict": str(LE.MODELS["zeroshot"][0])}
            continue
        final = run_root / arm / "final"
        sd = final / "best_model_state_dict.pt"
        if not sd.is_file():
            print(f"skip {name}: {sd} missing (pull back with: bash slurm/sync_from_osc.sh genco-retrain)")
            continue
        if not (run_root / arm / "DONE").is_file():
            print(f"WARNING {name}: no DONE marker in {run_root / arm}; scoring the checkpoint anyway")
        ns = final / "normalizer_stats.pt"
        LE.MODELS[name] = (sd, ns if (use_norm and ns.is_file()) else None)
        meta[name] = {"state_dict": str(sd), "normalizer_used": bool(use_norm and ns.is_file()),
                      "normalizer_present": ns.is_file(), "done_marker": (run_root / arm / "DONE").is_file()}
    return meta


def tally(rows: list[dict], models: list[str]) -> str:
    by = {(r["grid"], r["model"]): r for r in rows if "error" not in r}
    out = ["# Zero-shot tally on the 15 held-out grids (generated by score_retrain.py)", "",
           "Beats DC = lower than DC. Residual: graphkit active residual (MW). Branch angle: raw prediction, mean "
           "absolute branch angle difference error (deg). |V|: slack and PV magnitudes put back (pu).", "",
           "| model | grids scored | residual: beats DC | branch angle: beats DC | V: beats DC |", "|---|---|---|---|---|"]
    for m in models:
        g = [x for x in HELDOUT15 if (x, m) in by]
        res = sum(by[(x, m)]["genco_active_res_mw"] < by[(x, m)]["dc_active_res_mw"] for x in g)
        dva = sum(by[(x, m)]["errors"]["genco"]["branch_dva_mae_deg"] < by[(x, m)]["errors"]["dc"]["branch_dva_mae_deg"] for x in g)
        vm = sum(by[(x, m)]["errors"]["genco_pinned"]["vm_mae_pu"] < by[(x, m)]["errors"]["dc"]["vm_mae_pu"] for x in g)
        out.append(f"| {m} | {len(g)} | {res} | {dva} | {vm} |")
    out += ["", "## Per grid, ratio to DC (residual / branch angle / V)", "",
            "| grid | " + " | ".join(models) + " |", "|---|" + "---|" * len(models)]
    for x in HELDOUT15:
        cells = []
        for m in models:
            r = by.get((x, m))
            if r is None:
                cells.append("n/a")
                continue
            e = r["errors"]
            cells.append(f"{r['genco_active_res_mw'] / r['dc_active_res_mw']:.2f} / "
                         f"{e['genco']['branch_dva_mae_deg'] / e['dc']['branch_dva_mae_deg']:.2f} / "
                         f"{e['genco_pinned']['vm_mae_pu'] / e['dc']['vm_mae_pu']:.2f}")
        out.append(f"| {x} | " + " | ".join(cells) + " |")
    # identity control: an aliased arm must reproduce zeroshot
    for m in models:
        if m == "zeroshot":
            continue
        pairs = [(by[(x, m)], by[(x, "zeroshot")]) for x in HELDOUT15 if (x, m) in by and (x, "zeroshot") in by]
        if not pairs:
            continue
        d = max(abs(a["genco_active_res_mw"] - b["genco_active_res_mw"]) / max(abs(b["genco_active_res_mw"]), 1e-12)
                for a, b in pairs)
        out.append("")
        out.append(f"Largest relative residual difference {m} vs zeroshot over {len(pairs)} grids: {d:.2e}"
                   + ("  (identical to float noise: expected only for an --alias control)" if d < 1e-4 else ""))
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--run-root", type=Path, default=REPO / "experiments/genco-retrain")
    ap.add_argument("--grids", nargs="*", default=HELDOUT15)
    ap.add_argument("--models", nargs="*", help="default: zeroshot plus every registered arm")
    ap.add_argument("--use-arm-normalizer", action="store_true")
    ap.add_argument("--alias", nargs="*", default=[], help="control: retrain_fixed=released")
    a = ap.parse_args()
    a.run_root = a.run_root.resolve()   # graphkit runs in another cwd: relative checkpoint paths break (found 10-19)
    alias = dict(x.split("=", 1) for x in a.alias)
    meta = register(a.run_root, a.use_arm_normalizer, alias)
    models = a.models or ["zeroshot"] + sorted(meta)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "run_meta.json").write_text(json.dumps({"models": models, "arms": meta, "grids": a.grids,
                                                      "run_root": str(a.run_root)}, indent=1))
    res_path = a.out / "results.jsonl"
    done = set()
    if res_path.exists():
        done = {(r["grid"], r["model"]) for r in map(json.loads, res_path.read_text().splitlines()) if "error" not in r}
    for g in a.grids:
        for m in models:
            if (g, m) in done:
                continue
            try:
                r = LE.evaluate(g, m, LE.WORK / "mlruns-retrain")
            except Exception as exc:  # recorded, not raised: one grid must not stop the rest
                r = {"grid": g, "model": m, "error": f"{type(exc).__name__}: {exc}"}
            with res_path.open("a") as fh:
                fh.write(json.dumps(r) + "\n")
            print(json.dumps({k: r.get(k) for k in ("grid", "model", "genco_active_res_mw", "dc_active_res_mw", "error")}),
                  flush=True)
    rows = [json.loads(line) for line in res_path.read_text().splitlines()]
    (a.out / "tally.md").write_text(tally(rows, models))
    print((a.out / "tally.md").read_text())


if __name__ == "__main__":
    main()
