"""Zero-shot scoring of arbitrary GENCO state dicts on datakit grids, with the post's pipeline (``ladder_eval``).

Transfer experiment (the study plan): the same scorer for VALIDATION (RTE trees, checkpoint and arm
selection) and for the one-time EVALUATION on the 15 held-out grids. Generalizes ``score_retrain`` (which only knows
the two retrain arms). Released checkpoint = model name ``zeroshot`` (no normalizer file, as everywhere in the post).

    python -m genco_challenge.score_ckpts --out DIR --ckpt NAME=path/to/state.pt [NAME=...] \
        [--grids g1 g2 ...] [--data-root data/external/genco-ladder/data] [--with-released]

Writes DIR/results.jsonl (one row per model x grid, ``ladder_eval.evaluate`` rows) and DIR/tally.md (per grid: ratio
to DC of branch-angle error, |V| error and active residual; median over grids). Resumable: (grid, model) pairs
already in results.jsonl are skipped.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from genco_challenge import ladder_eval as LE
from genco_challenge.score_retrain import HELDOUT15


def ratios(row: dict) -> dict:
    """Ratios to DC exactly as score_retrain's tally: residual = graphkit active residual; branch angle = raw
    prediction's mean absolute branch angle-difference error; |V| = slack and PV magnitudes put back (genco_pinned)."""
    e = row["errors"]
    return {"res": row["genco_active_res_mw"] / row["dc_active_res_mw"],
            "angle": e["genco"]["branch_dva_mae_deg"] / e["dc"]["branch_dva_mae_deg"],
            "vm": e["genco_pinned"]["vm_mae_pu"] / e["dc"]["vm_mae_pu"]}


def tally(rows: list[dict], models: list[str], grids: list[str]) -> str:
    by = {(r["grid"], r["model"]): ratios(r) for r in rows}
    L = ["# Zero-shot ratios to DC (generated by score_ckpts.py; lower is better)", "",
         "| model | grids | median branch-angle ratio | branch angle beats DC | V beats DC | residual beats DC |",
         "|---|---|---|---|---|---|"]
    for m in models:
        g = [by[(x, m)] for x in grids if (x, m) in by]
        if not g:
            continue
        a = np.array([x["angle"] for x in g]); v = np.array([x["vm"] for x in g]); r = np.array([x["res"] for x in g])
        L.append(f"| {m} | {len(g)} | {np.nanmedian(a):.3f} | {int((a < 1).sum())} | {int((v < 1).sum())} | {int((r < 1).sum())} |")
    L += ["", "| grid | " + " | ".join(models) + " |", "|---|" + "---|" * len(models)]
    for x in grids:
        L.append(f"| {x} | " + " | ".join(
            (lambda q: f"{q['res']:.2f} / {q['angle']:.2f} / {q['vm']:.2f}")(by[(x, m)]) if (x, m) in by else "-"
            for m in models) + " |")
    L += ["", "Per-grid cells: residual / branch angle / V, each as a ratio to DC."]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--ckpt", nargs="*", default=[], help="NAME=path to a state dict")
    ap.add_argument("--grids", nargs="*", default=HELDOUT15)
    ap.add_argument("--data-root", type=Path, default=None, help="default: ladder_eval's data/external/genco-ladder/data")
    ap.add_argument("--with-released", action="store_true", help="also score the released checkpoint (zeroshot)")
    a = ap.parse_args()
    models = (["zeroshot"] if a.with_released else [])
    for spec in a.ckpt:
        name, path = spec.split("=", 1)
        p = Path(path).resolve()
        if not p.is_file():
            raise SystemExit(f"missing checkpoint {p}")
        LE.MODELS[name] = (p, None)
        models.append(name)
    a.out.mkdir(parents=True, exist_ok=True)
    res = a.out / "results.jsonl"
    done = set()
    rows = []
    if res.exists():
        rows = [json.loads(x) for x in res.read_text().splitlines() if x.strip()]
        # failed rows are retried (audit R1-F6); a row counts as done only for the SAME checkpoint path (transfer R2-F6;
        # legacy rows without "ckpt" still count, as before)
        done = {(r["grid"], r["model"], r.get("ckpt")) for r in rows if not r.get("error")}
    mlruns = (a.out / "mlruns").resolve()
    (a.out / "run_meta.json").write_text(json.dumps(
        {"models": {m: str(LE.MODELS[m][0]) for m in models}, "grids": a.grids,
         "data_root": str(a.data_root) if a.data_root else None}, indent=1))
    for g in a.grids:
        for m in models:
            ck = str(LE.MODELS[m][0])
            if (g, m, ck) in done or (g, m, None) in done:
                continue
            try:
                row = LE.evaluate(g, m, mlruns, data_root=a.data_root.resolve() if a.data_root else None)
            except Exception as ex:          # one failed grid must not lose the others; recorded, never silent
                row = {"grid": g, "model": m, "error": repr(ex)}
                print("ERROR", g, m, ex, flush=True)
            row["ckpt"] = ck
            with res.open("a") as fh:
                fh.write(json.dumps(row, default=float) + "\n")
            rows.append(row)
            print(g, m, "ok" if "error" not in row else "error", flush=True)
    good = [r for r in rows if "error" not in r]
    (a.out / "tally.md").write_text(tally(good, models, a.grids))
    print((a.out / "tally.md").read_text())


if __name__ == "__main__":
    main()
