"""Leakage check for the transfer experiment (the study plan section 2). Pre-registered rule:
a training/validation grid or replay subgrid is DROPPED if, against any of the 15 held-out grids, the case name
matches, the bus count matches, or the Jaccard overlap of branch (r, x) multisets (pu, rounded to 1e-4) is >= 0.3.

    python leakage_check.py            # writes leakage.md + leakage.json next to this file
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO / "core"))
from grid_ops.testbeds import load_case  # noqa: E402

HELDOUT15 = [
    "pglib_opf_case5_pjm", "pglib_opf_case14_ieee", "pglib_opf_case24_ieee_rts", "pglib_opf_case30_ieee",
    "pglib_opf_case39_epri", "pglib_opf_case57_ieee", "pglib_opf_case73_ieee_rts", "pglib_opf_case89_pegase",
    "pglib_opf_case118_ieee", "pglib_opf_case162_ieee_dtc", "pglib_opf_case240_pserc", "pglib_opf_case300_ieee",
    "pglib_opf_case1354_pegase", "pglib_opf_case2736sp_k", "pglib_opf_case3120sp_k",
]
TRAIN = ["1-HV-mixed--0-no_sw", "1-HV-mixed--1-no_sw", "1-HV-mixed--2-no_sw", "1-HV-urban--0-no_sw",
         "1-HV-urban--1-no_sw", "1-HV-urban--2-no_sw", "pglib_opf_case500_goc", "pglib_opf_case793_goc",
         "pglib_opf_case2000_goc", "pglib_opf_case2312_goc", "pglib_opf_case2742_goc", "pglib_opf_case3022_goc",
         "pglib_opf_case3970_goc", "pglib_opf_case4020_goc", "pglib_opf_case4601_goc", "pglib_opf_case4619_goc",
         "pglib_opf_case4837_goc", "pglib_opf_case4917_goc", "pglib_opf_case9591_goc",
         "pglib_opf_case5658_epigrids", "pglib_opf_case7336_epigrids"]
VALID = ["case1888rte", "case2848rte", "case6470rte", "case6495rte", "case6515rte"]
SECONDARY = ["case4gs", "case6ww", "case9", "case145", "case2869pegase", "pglib_opf_case8387_pegase", "case9241pegase"]
EVAL_TREES = REPO / "data/external/genco-pf-pretraining-eval"   # the 31 sampled GENCO pretraining subgrids (replay pool)
THR = 0.3
# revised 2026-10-19 21:25: EPIGRIDS -> train, RTE -> validation (GENCO pretraining already contains EPIGRIDS subgrids)


def fp_net(name):
    import pandapower as pp
    net = load_case(name)
    try:                                  # net._ppc (pu, system base) is built before solving, so it exists either way
        pp.runpp(net, init="flat", max_iteration=1)
    except Exception:
        pass
    ppc = net._ppc
    br = ppc["branch"]
    rx = Counter((round(float(r.real), 4), round(float(x.real), 4)) for r, x in zip(br[:, 2], br[:, 3]))
    return len(ppc["bus"]), rx


def fp_tables(d):
    br = pd.read_parquet(d / "raw/branch_data.parquet", columns=["scenario", "r", "x"])
    br = br[br.scenario == br.scenario.min()]
    b = pd.read_parquet(d / "raw/bus_data.parquet", columns=["scenario", "bus"])
    nb = int((b.scenario == b.scenario.min()).sum())
    return nb, Counter((round(float(r), 4), round(float(x), 4)) for r, x in zip(br.r, br.x))


def jac(a, b):
    inter = sum((a & b).values()); uni = sum((a | b).values())
    return inter / uni if uni else 0.0


def main():
    held = {h: fp_net(h) for h in HELDOUT15}
    cand = {n: ("train", fp_net(n)) for n in TRAIN}
    cand.update({n: ("valid", fp_net(n)) for n in VALID})
    cand.update({n: ("secondary", fp_net(n)) for n in SECONDARY})
    for d in sorted(p for p in EVAL_TREES.glob("subnet_*") if (p / "raw").is_dir()):
        cand[d.name] = ("replay-pool", fp_tables(d))
    rows = []
    for n, (role, (nb, rx)) in cand.items():
        worst = max(((jac(rx, hrx), h, hnb) for h, (hnb, hrx) in held.items()), key=lambda t: t[0])
        same_n = [h for h, (hnb, _) in held.items() if hnb == nb]
        name_hit = [h for h in HELDOUT15 if n.replace("pglib_opf_", "").split("_")[0] == h.replace("pglib_opf_", "").split("_")[0]]
        drop = worst[0] >= THR or bool(same_n) or bool(name_hit)
        rows.append(dict(grid=n, role=role, buses=nb, max_jaccard=round(worst[0], 4), vs=worst[1],
                         same_bus_count=same_n, name_match=name_hit, drop=drop))
    L = ["# Leakage check vs the 15 held-out grids (generated by leakage_check.py)", "",
         f"Rule: drop if name match, bus-count match, or branch (r, x) multiset Jaccard >= {THR}.", "",
         "| grid | role | buses | max Jaccard | vs | bus-count match | name match | DROP |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['grid']} | {r['role']} | {r['buses']} | {r['max_jaccard']} | {r['vs']} | "
                 f"{','.join(r['same_bus_count']) or '-'} | {','.join(r['name_match']) or '-'} | {'DROP' if r['drop'] else 'keep'} |")
    (HERE / "leakage.md").write_text("\n".join(L) + "\n")
    json.dump(rows, open(HERE / "leakage.json", "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
