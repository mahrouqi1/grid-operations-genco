"""Pre-registered go/no-go (protocol.json section go_no_go), criteria 1-4 on the locked 15; criterion 5
(in-distribution preservation) is scored separately and only matters if 1-4 pass. Released baseline = the 'zeroshot'
rows of results/2026-10-19-genco-retrain-scoring/zeroshot/results.jsonl (same ladder_eval pipeline; score_ckpts
reproduces its tally exactly). UNAUDITED."""
import json
from pathlib import Path

import numpy as np

import os
HERE = Path(__file__).resolve().parent
SUF = "-rescue" if os.environ.get("RESCUE") == "1" else ""   # protocol-rescue.json
H = json.load(open(HERE.parents[0] / "2026-10-19-genco-retrain-scoring/zeroshot/run_meta.json"))["grids"]


def rows(p):
    return [json.loads(l) for l in open(p) if l.strip()]


def ratios(r):
    e = r["errors"]
    return (e["genco"]["branch_dva_mae_deg"] / e["dc"]["branch_dva_mae_deg"],
            e["genco_pinned"]["vm_mae_pu"] / e["dc"]["vm_mae_pu"],
            r["genco_active_res_mw"] / r["dc_active_res_mw"],
            e["genco"]["branch_dva_mae_deg"])


rel = {r["grid"]: ratios(r) for r in rows(HERE.parents[0] / "2026-10-19-genco-retrain-scoring/zeroshot/results.jsonl")
       if r["model"] == "zeroshot" and not r.get("error")}
sel = json.load(open(HERE / f"selection{SUF}.json"))
arms = {}
for run in sel["runs"]:
    arm = run.rsplit("_s", 1)[0]
    if sel["runs"][run]["selected"].endswith("_step0"):   # audit R1-F1: a run that selects step 0 IS the released model
        R = dict(rel)
    else:
        R = {r["grid"]: ratios(r) for r in rows(HERE / f"heldout{SUF}" / run / "results.jsonl") if not r.get("error")}
    arms.setdefault(arm, {})[run] = R
rel_med = float(np.median([rel[g][0] for g in H]))
out = {"released": {"median_angle_ratio": rel_med, "angle_beats_dc": int(sum(rel[g][0] < 1 for g in H)),
                    "V_beats_dc": int(sum(rel[g][1] < 1 for g in H)), "res_beats_dc": int(sum(rel[g][2] < 1 for g in H))}}
for arm, runs in sorted(arms.items()):
    seeds = sorted(runs)
    ang = np.array([[runs[s][g][0] for g in H] for s in seeds])
    vm = np.array([[runs[s][g][1] for g in H] for s in seeds])
    res = np.array([[runs[s][g][2] for g in H] for s in seeds])
    err = np.array([[runs[s][g][3] for g in H] for s in seeds])
    m_ang, m_vm, m_err = ang.mean(0), vm.mean(0), err.mean(0)
    per_seed_med = [float(np.median(a)) for a in ang]
    c1 = float(np.median(m_ang)); c2 = int(sum(m_err[i] < rel[g][3] for i, g in enumerate(H)))
    c3 = [1 - m / rel_med for m in per_seed_med]; c4 = int(sum(m_vm < 1))
    out[arm] = {"seeds": seeds, "median_seedmean_angle_ratio": c1, "drop_vs_released": 1 - c1 / rel_med,
                "grids_better_than_released": c2, "per_seed_median_drop": c3, "V_beats_dc": c4,
                "angle_beats_dc": int(sum(m_ang < 1)), "res_beats_dc": int(sum(res.mean(0) < 1)),
                "crit": {"1_median<=2.77": c1 <= 2.77, "2_breadth>=11": c2 >= 11, "3_each_seed_drop>=15%": all(d >= 0.15 for d in c3),
                         "4_V>=12": c4 >= 12},
                "per_grid_seedmean_angle_ratio": {g: float(m_ang[i]) for i, g in enumerate(H)}}
goarm = sel["go_no_go_arm"]
out["go_no_go_arm"] = goarm
out["criteria_1_to_4_pass"] = all(out[goarm]["crit"].values())
json.dump(out, open(HERE / f"go_no_go{SUF}.json", "w"), indent=1)
L = ["# Go/no-go on the locked 15 (generated by go_no_go.py; UNAUDITED)", "",
     f"Released: median branch-angle ratio to DC {rel_med:.3f}; beats DC on angle {out['released']['angle_beats_dc']}, |V| {out['released']['V_beats_dc']}, residual {out['released']['res_beats_dc']} of 15.", "",
     "| arm | median seed-mean angle ratio | drop vs released | grids better than released | per-seed median drop | \\|V\\| beats DC | angle beats DC | crit 1 / 2 / 3 / 4 |",
     "|---|---|---|---|---|---|---|---|"]
for arm in [a for a in ("Rlr", "Rfrz", "Rrep", "c", "m", "a", "b", "D", "C00", "C01") if a in out]:
    o = out[arm]; c = o["crit"]
    L.append(f"| {arm}{' (selected)' if arm == goarm else ''} | {o['median_seedmean_angle_ratio']:.3f} | {100*o['drop_vs_released']:.1f}% | {o['grids_better_than_released']} | "
             + " / ".join(f"{100*d:.0f}%" for d in o["per_seed_median_drop"]) + f" | {o['V_beats_dc']} | {o['angle_beats_dc']} | "
             + " / ".join("pass" if v else "FAIL" for v in c.values()) + " |")
L += ["", f"Validation-selected arm: **{goarm}**. Criteria 1-4: **{'PASS' if out['criteria_1_to_4_pass'] else 'FAIL -> NO-GO'}**"
      + ("" if not out["criteria_1_to_4_pass"] else " (criterion 5, preservation, still to score)")]
(HERE / f"go_no_go{SUF}.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
