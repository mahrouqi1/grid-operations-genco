"""B primary metric per protocol.json: collapse reproduction = share of hidden collapsed PQ buses predicted < 0.5 pu
under the pretraining mask, pooled over the 7 TRAINING subgrids (the 9 affected minus subnet_case9591_goc_idx_12,
dropped from both arms, and the validation subgrid subnet_case19402_goc_idx_47), weighted by hidden collapsed buses,
per mask seed 1000-1002; plus normal-scenario hidden-PQ |V| MAE (preservation test 2). UNAUDITED.
step0 = the released weights in both arms (state_step0 saved before any update; the two files are byte-identical), so
the complete published_step0 run is used for both."""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
TRAIN7 = {"subnet_case4837_goc_idx_35", "subnet_case20758_epigrids_idx_49", "subnet_case5658_epigrids_idx_8",
          "subnet_case4837_goc_idx_28", "subnet_case10480_goc_idx_40", "subnet_case4837_goc_idx_37",
          "subnet_case10480_goc_idx_26"}


def pooled(path):
    G = [json.loads(l) for l in open(path) if l.strip()]
    G = [g for g in G if g["grid"] in TRAIN7]
    out = {"grids": len(G)}
    for seed in (1000, 1001, 1002):
        runs = [r for g in G for r in g["runs"] if r["mask"] == "pre" and r["seed"] == seed]
        w = np.array([r["n_low_hidden"] for r in runs], float)
        wn = np.array([r["normal"]["n_hidden_pq"] for r in runs], float)
        out[seed] = {"hidden_collapsed": int(w.sum()),
                     "frac_lt_0.5": float(np.average([r["frac_pred_lt_0.5"] for r in runs], weights=w)),
                     "normal_vm_mae": float(np.average([r["normal"]["mae_vs_label"] for r in runs], weights=wn))}
    return out


rows = []
for arm in ("fixed", "published"):
    for st in ("step0", "step25", "step50", "step100", "step250", "step500", "step1000", "final"):
        f = HERE / "pmask" / (f"published_step0.jsonl" if st == "step0" else f"{arm}_{st}.jsonl")
        if f.exists():
            rows.append((arm, st, pooled(f)))
L = ["# B collapse reproduction (generated by pool.py; UNAUDITED)", "",
     "Pooled over the 7 training subgrids, weighted by hidden collapsed PQ buses; pretraining mask, seeds 1000/1001/1002.", "",
     "| arm | state | subgrids | collapsed buses predicted < 0.5 pu (seed 1000 / 1001 / 1002) | normal-scenario hidden \\|V\\| MAE (pu, same seeds) |",
     "|---|---|---|---|---|"]
for arm, st, o in rows:
    L.append(f"| {arm} | {st} | {o['grids']} | " + " / ".join(f"{o[s]['frac_lt_0.5']:.3f}" for s in (1000, 1001, 1002)) + " | "
             + " / ".join(f"{o[s]['normal_vm_mae']:.4f}" for s in (1000, 1001, 1002)) + " |")
(HERE / "pooled.md").write_text("\n".join(L) + "\n")
json.dump([{"arm": a, "state": s, **{str(k): v for k, v in o.items()}} for a, s, o in rows], open(HERE / "pooled.json", "w"), indent=1)
print("\n".join(L))
