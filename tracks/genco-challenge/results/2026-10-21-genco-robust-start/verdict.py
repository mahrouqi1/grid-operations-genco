"""Summary table + success-test verdict from per_scenario/*.csv and protocol.json (no hand computation).
    python verdict.py  -> summary.csv, summary.md, verdict.json, verdict.md"""
import json
from pathlib import Path
import numpy as np, pandas as pd
HERE = Path(__file__).resolve().parent
P = json.loads((HERE / "protocol.json").read_text())
FAM = P["grids"]; BIG = set(P["grids_ge_5000_buses"])
CLASSICAL, GENCO = ["flat", "dc", "fd2"], ["genco_vmdc", "genco_full"]
df = pd.concat([pd.read_csv(f) for f in sorted((HERE / "per_scenario").glob("*.csv"))], ignore_index=True)
grids = [g for f in FAM.values() for g in f]
rows = []
for (g, s), d in df.groupby(["grid", "start"]):
    n = len(d)
    conv = d[d["status"] != "diverged"]
    rows.append(dict(grid=g, start=s, n=n, n_bus=int(d["n_bus"].iloc[0]), verified_pct=100 * (d.status == "verified_root").mean(),
                     other_root_pct=100 * (d.status == "other_root").mean(), diverged_pct=100 * (d.status == "diverged").mean(),
                     median_iters=float(d.iterations.median()), median_iters_converged=float(conv.iterations.median()) if len(conv) else np.nan,
                     median_start_ms=1e3 * d.start_s.median(), median_newton_ms=1e3 * d.newton_s.median(), median_total_ms=1e3 * d.total_s.median()))
S = pd.DataFrame(rows).set_index(["grid", "start"])
S.reset_index().to_csv(HERE / "summary.csv", index=False)
rate = S["verified_pct"].unstack("start").reindex(grids)
# single GENCO arm for the verdict: higher pooled verified-root rate over all grids (ties -> genco_vmdc)
pooled = {a: float(rate[a].mean()) for a in GENCO}
arm = "genco_vmdc" if pooled["genco_vmdc"] >= pooled["genco_full"] else "genco_full"
bestc = rate[CLASSICAL].max(axis=1)
fam_rows, passing = [], []
for fam, gl in FAM.items():
    fg, fc = float(rate.loc[gl, arm].mean()), float(rate.loc[gl, CLASSICAL].mean().max())
    cstart = rate.loc[gl, CLASSICAL].mean().idxmax()
    ok = fg - fc >= 10.0
    if ok:
        passing.append(fam)
    fam_rows.append(dict(family=fam, genco_rate=fg, best_classical=cstart, best_classical_rate=fc, diff_pts=fg - fc, passes_10pts=bool(ok)))
rest = [g for fam, gl in FAM.items() if fam not in passing for g in gl]
within2_rest = {g: bool(rate.loc[g, arm] >= bestc[g] - 2.0) for g in rest}
within2_all = {g: bool(rate.loc[g, arm] >= bestc[g] - 2.0) for g in grids}
cond_a = len(passing) >= 2 and all(within2_rest.values())
cond_a_strict = len(passing) >= 2 and all(within2_all.values())
b_rows = []
for g in grids:
    if g not in BIG:
        continue
    eq = bool(rate.loc[g, arm] >= bestc[g] - 2.0)
    cands = [c for c in CLASSICAL if rate.loc[g, c] >= bestc[g] - 2.0]
    ref = min(cands, key=lambda c: S.loc[(g, c), "median_total_ms"])
    t_g, t_c = float(S.loc[(g, arm), "median_total_ms"]), float(S.loc[(g, ref), "median_total_ms"])
    both0 = bool(bestc[g] == 0 and rate.loc[g, arm] == 0)
    b_rows.append(dict(grid=g, genco_rate=float(rate.loc[g, arm]), best_classical_rate=float(bestc[g]), equal_convergence=eq, ref_classical=ref,
                       genco_total_ms=t_g, ref_total_ms=t_c, time_ratio=t_g / t_c, faster_by_20pct=bool(t_g <= 0.8 * t_c), both_zero=both0,
                       satisfied=bool(eq and t_g <= 0.8 * t_c and not both0)))
cond_b = bool(b_rows) and all(r["satisfied"] for r in b_rows)
V = dict(arm_used=arm, pooled_rate_by_genco_arm=pooled, families=fam_rows, families_passing=passing,
         per_grid_within_2pts_of_best_classical_all_grids=within2_all, non_passing_family_grids_within_2pts=within2_rest,
         condition_a=bool(cond_a), condition_a_strict=bool(cond_a_strict), condition_b_rows=b_rows, condition_b=bool(cond_b),
         verdict="GO" if (cond_a or cond_b) else "NO-GO")
(HERE / "verdict.json").write_text(json.dumps(V, indent=1))
L = [f"# Verdict (generated by verdict.py): **{V['verdict']}**", "",
     f"GENCO arm used: `{arm}` (pooled verified-root rate over all grids: " + ", ".join(f"{a} {v:.1f}%" for a, v in pooled.items()) + ")", "",
     f"- Condition (a): **{cond_a}** (families passing 10-pt test: {passing or 'none'}; strict variant: {cond_a_strict})",
     f"- Condition (b): **{cond_b}**", "", "## Condition (a): family rates (verified-root %, mean over the family's grids)", "",
     "| family | GENCO | best classical | its rate | diff (pts) | passes |", "|---|---|---|---|---|---|"]
L += [f"| {r['family']} | {r['genco_rate']:.1f} | {r['best_classical']} | {r['best_classical_rate']:.1f} | {r['diff_pts']:+.1f} | {r['passes_10pts']} |" for r in fam_rows]
L += ["", "## Condition (b): grids >= 5,000 buses", "",
      "| grid | GENCO % | best classical % | equal conv. | ref classical | GENCO ms | ref ms | ratio | >=20% faster | satisfied |", "|---|---|---|---|---|---|---|---|---|---|"]
L += [f"| {r['grid']} | {r['genco_rate']:.0f} | {r['best_classical_rate']:.0f} | {r['equal_convergence']} | {r['ref_classical']} | {r['genco_total_ms']:.0f} | {r['ref_total_ms']:.0f} | {r['time_ratio']:.2f} | {r['faster_by_20pct']} | {r['satisfied']} |" for r in b_rows]
(HERE / "verdict.md").write_text("\n".join(L) + "\n")
T = ["| grid | buses | start | verified % | other root % | diverged % | median iters | median start ms | median Newton ms | median total ms |", "|---|---|---|---|---|---|---|---|---|---|"]
for g in grids:
    for st in CLASSICAL + GENCO:
        r = S.loc[(g, st)]
        T.append(f"| {g} | {int(r.n_bus)} | {st} | {r.verified_pct:.0f} | {r.other_root_pct:.0f} | {r.diverged_pct:.0f} | {r.median_iters:.0f} | {r.median_start_ms:.1f} | {r.median_newton_ms:.1f} | {r.median_total_ms:.1f} |")
(HERE / "summary.md").write_text("\n".join(T) + "\n")
print("\n".join(L)); print(); print("\n".join(T))
