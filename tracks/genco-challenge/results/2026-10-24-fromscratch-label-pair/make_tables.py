"""Tables + figure for the from-scratch label pair (generated; UNAUDITED).
Reads: rte/<arm>/results.jsonl (2 RTE validation grids, every 2,000 updates), l15/<arm>/results.jsonl (locked 15 at the
selected checkpoints), pooled_pmask.json (pool_pmask.py), flat_guess.json, experiments/.../progress.jsonl + mlruns metrics.
Writes: tables.md, series.json, fig_collapse_and_error.png.  Dedupes (grid, model) rows (two scoring streams)."""
import json
import re
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
EXP = REPO / "experiments/genco-fromscratch-pair"
ARMS = ("original", "corrected")
COL = {"corrected": "#56B4E9", "original": "#3b3b3b"}
NAME = {"corrected": "corrected labels", "original": "original labels"}


def load(p):
    return [json.loads(l) for l in open(p) if l.strip()] if Path(p).exists() else []


def ratios(r):
    e = r["errors"]
    return {"res": r["genco_active_res_mw"] / r["dc_active_res_mw"],
            "angle": e["genco"]["branch_dva_mae_deg"] / e["dc"]["branch_dva_mae_deg"],
            "vm": e["genco_pinned"]["vm_mae_pu"] / e["dc"]["vm_mae_pu"]}


def tag_step(tag, final_step):
    return final_step if tag == "final" else int(tag.replace("step", ""))


FINAL = {a: int(open(EXP / a / "FINAL_STEP").read()) for a in ARMS}


def score_series(sub):
    """{arm: {step: {grid: ratios}}} from <sub>/<arm>/results.jsonl, model name <arm>_<tag>."""
    out = {}
    for a in ARMS:
        d = {}
        for r in load(HERE / sub / a / "results.jsonl") + load(HERE / (sub + "_rev") / a / "results.jsonl"):
            if r.get("error"):
                continue
            tag = r["model"].split("_", 1)[1]
            d.setdefault(tag_step(tag, FINAL[a]), {})[r["grid"]] = ratios(r)
        out[a] = d
    return out


def med(d, key):
    v = [x[key] for x in d.values()]
    return float(np.median(v)), len(v)


def curve(path_glob, key="Validation loss"):
    pass


def metric_series(arm, name):
    base = EXP / "mlm" / arm
    f = next(base.glob(f"*/*/metrics/{name}"))
    rows = [l.split() for l in open(f) if l.strip()]   # mlflow file store: ts value step
    return {int(r[-1]): float(r[-2]) for r in rows}


def main():
    rte, l15 = score_series("rte"), score_series("l15")
    P = json.load(open(HERE / "pooled_pmask.json"))
    flat = json.load(open(HERE / "flat_guess.json"))
    pm = {(r["arm"], tag_step(r["tag"], FINAL[r["arm"]])): r for r in P}
    L = ["# Tables (generated by make_tables.py; UNAUDITED)", ""]
    S = {"final": FINAL}

    # --- learning curves
    prog = {a: [json.loads(l) for l in open(EXP / a / "progress.jsonl")] for a in ARMS}
    L += ["## Training: LR and loss", "", "| arm | final update | final LR | train loss, mean of last 20 logged | updates logged with LR != 5e-4 after warm-up |", "|---|---|---|---|---|"]
    for a in ARMS:
        p = prog[a]
        bad = sum(1 for r in p if r["step"] > 1000 and abs(r["lr"] - 5e-4) > 1e-12)
        L.append(f"| {a} | {FINAL[a]} | {p[-1]['lr']:g} | {np.mean([r['loss'] for r in p[-20:]]):.4f} | {bad} |")
    S["val_loss"] = {}
    try:
        for a in ARMS:
            S["val_loss"][a] = metric_series(a, "Validation loss")
        L += ["", "Validation loss on the 2 unaffected validation subgrids (graphkit's logged 'Validation loss', epoch-end steps; the arms log at the same steps; nearest logged step to each matched update):", "",
              "| update (nearest logged) | original | corrected |", "|---|---|---|"]
        for tgt in (12000, 24000, 48000, 96000, 114000):
            k = min(S["val_loss"]["original"], key=lambda x: abs(x - tgt))
            L.append(f"| {tgt} ({k}) | {S['val_loss']['original'][k]:.3f} | {S['val_loss']['corrected'][k]:.3f} |")
        L.append("| last logged | " + " | ".join(f"{max(S['val_loss'][a])}: {S['val_loss'][a][max(S['val_loss'][a])]:.3f}" for a in ARMS) + " |")
    except Exception as ex:   # noqa
        L.append(f"(validation-loss series not read: {ex!r})")

    # --- gate
    L += ["", "## Underfit gate at 12,000 updates", "",
          f"Flat 1.0 pu guess, |V| MAE at PQ buses of normal scenarios, 7 training subgrids pooled: {flat['pooled']['flat1_mae']:.4f} pu.", "",
          "| arm | model hidden-PQ |V| MAE on normal scenarios, 7 training subgrids (mean of mask seeds 1000-1002) | ratio to flat guess | verdict |", "|---|---|---|---|---|"]
    for a in ARMS:
        r = pm.get((a, 12000))
        if r:
            m = r["train7"]["mean_normal_vm_mae"]
            L.append(f"| {a} | {m:.4f} | {m / flat['pooled']['flat1_mae']:.2f} | {'pass' if m < 0.5 * flat['pooled']['flat1_mae'] else 'FAIL'} |")
    L += ["", "(Pass criterion used: MAE at most half of the flat-guess MAE, i.e. 'clearly below'; the protocol gives no number. Any ratio near or above 1 is a fail under any reading.)"]

    # --- pmask table
    L += ["", "## Collapse reproduction (m2) and normal-scenario error", "",
          "Share of hidden collapsed PQ buses with predicted |V| < 0.5 pu under the pretraining mask, pooled over the 7 training subgrids (mean over mask seeds 1000/1001/1002, range in brackets); all-9-subgrid share; normal-scenario hidden |V| MAE.", "",
          "| update | arm | collapse share (7 train) | [seed min-max] | collapse share (all 9) | normal |V| MAE (pu) | PF-task: share < 0.5 | PF-task: MAE to repaired root | PF-task: MAE to label | PF-task: buses closer to root |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    steps = sorted({s for (_, s) in pm})
    for s in steps:
        for a in ARMS:
            r = pm.get((a, s))
            if not r:
                continue
            t = r["train7"]
            sh = [t["seeds"][k]["frac_lt_0.5"] for k in t["seeds"]]
            pf = t.get("pf", {})
            L.append(f"| {s}{' (final)' if s == FINAL[a] else ''} | {a} | {t['mean_frac_lt_0.5']:.3f} | [{min(sh):.3f}-{max(sh):.3f}] | {r['all9']['mean_frac_lt_0.5']:.3f} | {t['mean_normal_vm_mae']:.4f} | "
                     + (f"{pf['frac_lt_0.5']:.3f} | {pf['mae_vs_root']:.3f} | {pf['mae_vs_label']:.3f} | {pf['frac_closer_to_root']:.3f} |" if pf else "- | - | - | - |"))

    # --- locked 15
    L += ["", "## Locked 15 (m1): median over grids of the ratio to DC (lower is better; 1 = same as DC)", "",
          "| update | arm | grids | branch angle | |V| | active residual |", "|---|---|---|---|---|---|"]
    steps15 = sorted({s for a in ARMS for s in l15[a]})
    for s in steps15:
        for a in ARMS:
            d = l15[a].get(s)
            if not d:
                continue
            L.append(f"| {s}{' (final)' if s == FINAL[a] else ''} | {a} | {len(d)} | " + " | ".join(f"{med(d, k)[0]:.3f}" for k in ("angle", "vm", "res")) + " |")
    # per-grid paired ratio corrected/original at matched updates
    L += ["", "Paired ratio corrected / original of the per-grid branch-angle ratio-to-DC, median over the grids scored in both arms (noise band: outside [0.62, 1.62] is the pre-registered m1 threshold):", "",
          "| update | grids | median corrected/original (angle) | (|V|) | (residual) |", "|---|---|---|---|---|"]
    S["l15_paired"] = {}
    for s in steps15:
        if s in l15["original"] and s in l15["corrected"]:
            g = sorted(set(l15["original"][s]) & set(l15["corrected"][s]))
            q = {k: float(np.median([l15["corrected"][s][x][k] / l15["original"][s][x][k] for x in g])) for k in ("angle", "vm", "res")}
            S["l15_paired"][s] = q
            L.append(f"| {s} | {len(g)} | {q['angle']:.2f} | {q['vm']:.2f} | {q['res']:.2f} |")

    # --- RTE
    L += ["", "## RTE validation (m1, 2 grids: case1888rte, case2848rte): ratio to DC of branch angle (mean of the 2 grids) and |V|", "",
          "| update | original angle | corrected angle | corr/orig angle | original |V| | corrected |V| |", "|---|---|---|---|---|---|"]
    stepsr = sorted(set(rte["original"]) | set(rte["corrected"]))
    S["rte"] = {a: {} for a in ARMS}
    for s in stepsr:
        row = {}
        for a in ARMS:
            d = rte[a].get(s, {})
            if len(d) == 2:
                row[a] = (np.mean([x["angle"] for x in d.values()]), np.mean([x["vm"] for x in d.values()]))
                S["rte"][a][s] = row[a]
        if len(row) == 2:
            L.append(f"| {s} | {row['original'][0]:.3f} | {row['corrected'][0]:.3f} | {row['corrected'][0] / row['original'][0]:.2f} | {row['original'][1]:.3f} | {row['corrected'][1]:.3f} |")
    (HERE / "tables.md").write_text("\n".join(L) + "\n")

    # --- figure (750 px wide; step 0 left out of the top panel: the untrained init predicts ~0 pu everywhere and so "reproduces" 100%)
    fig, ax = plt.subplots(2, 1, figsize=(7.5, 6.6), sharex=True, dpi=100)
    for a in ARMS:
        for panel, getter, ser in ((0, lambda s, a=a: 100 * pm[(a, s)]["train7"]["mean_frac_lt_0.5"], sorted(s for (aa, s) in pm if aa == a and s > 0)),
                                   (1, lambda s, a=a: med(l15[a][s], "angle")[0], sorted(l15[a]))):
            xm = [s for s in ser if s <= 114000]
            ax[panel].plot(xm, [getter(s) for s in xm], "-o", color=COL[a], lw=2, ms=6, label=NAME[a])
            xf = [s for s in ser if s > 114000]
            ax[panel].plot(xf, [getter(s) for s in xf], "o", mfc="white", mec=COL[a], mew=1.8, ms=7)
    ax[0].axhline(10, color="#999999", ls="--", lw=1)
    ax[0].text(2000, 10.4, "10%: both arms below this = uninformative", fontsize=9, color="#555555", ha="left", va="bottom")
    ax[0].set_ylabel("Hidden collapsed buses\nreproduced (%)", fontsize=10.5)
    ax[0].set_ylim(-0.5, 12.5)
    ax[1].axhline(1.0, color="#999999", ls="--", lw=1)
    ax[1].text(2000, 1.03, "same error as DC", fontsize=9, color="#555555", ha="left", va="bottom")
    ax[1].set_ylabel("Error on 15 held-out grids\n(branch angle, ratio to DC)", fontsize=10.5)
    ax[1].set_xlabel("Training updates (hollow = each arm's last update)", fontsize=10.5)
    ax[1].set_yscale("log"); ax[1].set_ylim(0.8, 12)
    ax[1].set_yticks([1, 2, 5, 10]); ax[1].set_yticklabels(["1", "2", "5", "10"])
    ax[1].set_xlim(0, 120000)
    for a_ in ax:
        a_.spines[["top", "right"]].set_visible(False)
        a_.tick_params(labelsize=9.5)
    ax[0].legend(frameon=False, fontsize=10, loc="upper right", bbox_to_anchor=(1.0, 0.74))
    fig.tight_layout()
    fig.savefig(HERE / "fig_collapse_and_error.png")
    json.dump({"rte": {a: {str(k): v for k, v in S["rte"][a].items()} for a in ARMS}, "l15_paired": {str(k): v for k, v in S["l15_paired"].items()}},
              open(HERE / "series.json", "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
